REVOKE ALL ON SEQUENCE public.friend_requests_id_seq, public.chat_messages_id_seq, public.comments_id_seq, public.comment_replies_id_seq, public.user_reports_id_seq, public.watch_progress_id_seq FROM anon, authenticated;
