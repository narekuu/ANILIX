-- Account-wide social and playback sync tables.
-- Existing users and account data are intentionally preserved.

CREATE TABLE IF NOT EXISTS public.friend_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  recipient_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','accepted','rejected','cancelled')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (sender_id <> recipient_id),
  UNIQUE (sender_id, recipient_id)
);
CREATE INDEX IF NOT EXISTS friend_requests_recipient_status_idx ON public.friend_requests(recipient_id,status,created_at DESC);
CREATE INDEX IF NOT EXISTS friend_requests_sender_status_idx ON public.friend_requests(sender_id,status,created_at DESC);

CREATE TABLE IF NOT EXISTS public.friendships (
  user_low_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  user_high_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_low_id,user_high_id),
  CHECK (user_low_id < user_high_id)
);
CREATE INDEX IF NOT EXISTS friendships_high_idx ON public.friendships(user_high_id);

CREATE TABLE IF NOT EXISTS public.chat_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  recipient_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  body text NOT NULL CHECK (char_length(body) BETWEEN 1 AND 4000),
  created_at timestamptz NOT NULL DEFAULT now(),
  read_at timestamptz,
  CHECK (sender_id <> recipient_id)
);
CREATE INDEX IF NOT EXISTS chat_messages_pair_idx ON public.chat_messages(
  LEAST(sender_id,recipient_id), GREATEST(sender_id,recipient_id), created_at DESC, id DESC
);
CREATE INDEX IF NOT EXISTS chat_messages_unread_idx ON public.chat_messages(recipient_id,read_at) WHERE read_at IS NULL;
CREATE INDEX IF NOT EXISTS chat_messages_sender_idx ON public.chat_messages(sender_id,created_at DESC);

CREATE TABLE IF NOT EXISTS public.comments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  content_id text NOT NULL,
  content_type text NOT NULL DEFAULT 'anime',
  title text NOT NULL,
  poster text,
  body text NOT NULL CHECK (char_length(body) BETWEEN 1 AND 3000),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS comments_content_idx ON public.comments(content_type,content_id,created_at DESC,id DESC);
CREATE INDEX IF NOT EXISTS comments_user_idx ON public.comments(user_id,created_at DESC);

CREATE TABLE IF NOT EXISTS public.comment_replies (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  comment_id bigint NOT NULL REFERENCES public.comments(id) ON DELETE CASCADE,
  user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  body text NOT NULL CHECK (char_length(body) BETWEEN 1 AND 2000),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS comment_replies_comment_idx ON public.comment_replies(comment_id,created_at,id);
CREATE INDEX IF NOT EXISTS comment_replies_user_idx ON public.comment_replies(user_id,created_at DESC);

CREATE TABLE IF NOT EXISTS public.user_reports (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reporter_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  target_user_id bigint REFERENCES public.users(id) ON DELETE SET NULL,
  target_type text NOT NULL CHECK (target_type IN ('user','comment','message','anime','other')),
  target_id text,
  reason text NOT NULL CHECK (char_length(reason) BETWEEN 3 AND 120),
  details text CHECK (details IS NULL OR char_length(details) <= 2000),
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open','reviewing','resolved','dismissed')),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS user_reports_status_idx ON public.user_reports(status,created_at DESC);
CREATE INDEX IF NOT EXISTS user_reports_reporter_idx ON public.user_reports(reporter_id,created_at DESC);
CREATE INDEX IF NOT EXISTS user_reports_target_user_idx ON public.user_reports(target_user_id,created_at DESC);

CREATE TABLE IF NOT EXISTS public.watch_progress (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  content_id text NOT NULL,
  content_type text NOT NULL DEFAULT 'anime',
  title text NOT NULL,
  poster text,
  episode text NOT NULL,
  position_seconds double precision NOT NULL DEFAULT 0 CHECK (position_seconds >= 0),
  duration_seconds double precision NOT NULL DEFAULT 0 CHECK (duration_seconds >= 0),
  progress double precision NOT NULL DEFAULT 0 CHECK (progress >= 0 AND progress <= 100),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(user_id,content_id,content_type,episode)
);
CREATE INDEX IF NOT EXISTS watch_progress_user_updated_idx ON public.watch_progress(user_id,updated_at DESC);

-- These tables are accessed only through the authenticated ANILIX backend.
-- Direct browser roles receive no table or sequence privileges.
